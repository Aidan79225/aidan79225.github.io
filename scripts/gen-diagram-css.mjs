// Regenerate src/styles/diagram-light.css from scripts/theme-map.mjs.
//   npm run theme:css
// The output is committed; edit the map, not the CSS.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { MAP, INLINE_STYLE_COLORS } from './theme-map.mjs';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src/styles/diagram-light.css');

const header = `/* GENERATED by scripts/gen-diagram-css.mjs — do not edit by hand.
   Source of truth: scripts/theme-map.mjs · regenerate with \`npm run theme:css\`.

   Inline SVG diagrams in posts carry dark-palette hex values as presentation
   attributes. A stylesheet rule always outranks a presentation attribute, so
   matching on the literal value repaints every diagram for the light skin
   without touching a single markdown file. */
`;

const lines = [header];
for (const [dark, light] of Object.entries(MAP)) {
  lines.push(
    `:root[data-theme="light"] :is(svg, svg *)[fill="${dark}" i] { fill: ${light}; }`,
    `:root[data-theme="light"] :is(svg, svg *)[stroke="${dark}" i] { stroke: ${light}; }`,
    `:root[data-theme="light"] :is(svg, svg *)[stop-color="${dark}" i] { stop-color: ${light}; }`,
  );
}

lines.push(
  '',
  '/* Post bodies also colour a few <strong>/<span> runs with inline styles;',
  '   only an !important declaration can outrank those. */',
);
for (const c of INLINE_STYLE_COLORS) {
  lines.push(`:root[data-theme="light"] .prose [style*="${c}" i] { color: ${MAP[c]} !important; }`);
}

await writeFile(OUT, lines.join('\n') + '\n');
console.log(`wrote ${OUT} (${Object.keys(MAP).length} colours)`);
